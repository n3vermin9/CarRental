export function getCopy(locale: Locale) {
  return locale === 'ru' ? ru : en;
}

export function carTypeLabel(locale: Locale, type: string) {
  const copy = getCopy(locale);
  return type === 'Economy' ? copy.economy : type === 'Comfort' ? copy.comfort : type === 'Business' ? copy.business : type;
}

export function dayCount(locale: Locale, count: number) {
  if (locale === 'en') return `${count} ${count === 1 ? 'day' : 'days'}`;
  const lastTwo = count % 100;
  const last = count % 10;
  const word = lastTwo >= 11 && lastTwo <= 14 ? 'дней' : last === 1 ? 'день' : last >= 2 && last <= 4 ? 'дня' : 'дней';
  return `${count} ${word}`;
}

export function tripCount(locale: Locale, count: number) {
  if (locale === 'en') return `${count} ${count === 1 ? 'rental' : 'rentals'}`;
  const lastTwo = count % 100;
  const last = count % 10;
  const word = lastTwo >= 11 && lastTwo <= 14 ? 'аренд' : last === 1 ? 'аренда' : last >= 2 && last <= 4 ? 'аренды' : 'аренд';
  return `${count} ${word}`;
}

export function minuteCount(locale: Locale, count: number, short = false) {
  if (locale === 'en') return `${count} ${short ? 'min' : count === 1 ? 'minute' : 'minutes'}`;
  if (short) return `${count} мин`;
  const lastTwo = count % 100;
  const last = count % 10;
  const word = lastTwo >= 11 && lastTwo <= 14 ? 'минут' : last === 1 ? 'минута' : last >= 2 && last <= 4 ? 'минуты' : 'минут';
  return `${count} ${word}`;
}

export function tripDate(locale: Locale, date: string) {
  if (locale === 'en') return date;
  if (date === 'Today') return 'Сегодня';
  return date.replace('Aug', 'авг.');
}

export function tripPlace(locale: Locale, place: string) {
  if (locale === 'en') return place;
  const places: Record<string, string> = {
    'Grozny Mall': 'Грозный Молл',
    'Minutka Square': 'Площадь Минутка',
    'Putin Avenue': 'Проспект Путина',
    'Flower Park': 'Парк Цветов',
    'Grozny City': 'Грозный-Сити',
    'Airport District': 'Район аэропорта',
  };
  return places[place] ?? place;
}
